"""Map native authored idle anatomy onto each player's already-dressed texture.

Only lower-body pixels move. Heads, hair, hats and palette choices stay native.
Output is a small source-pixel lookup, not a replacement character illustration.
"""
from pathlib import Path
from PIL import Image
import json

ROOT = Path(__file__).resolve().parents[1]
assets = ROOT / "public/assets"
run = Image.open(assets / "Adam_run_16x16.png").convert("RGBA")
idle = Image.open(assets / "Adam_idle_anim_16x16.png").convert("RGBA")
poses = {}
for direction, first, preferred in [("right", 0, 2), ("up", 6, 8), ("left", 12, 14), ("down", 18, 19)]:
    lookup = []
    for y in range(22, 32):
        for x in range(16):
            color = idle.getpixel((first * 16 + x, y))
            if not color[3]:
                lookup.append(-1)
                continue
            candidates = []
            for frame in range(first, first + 6):
                for sy in range(22, 32):
                    for sx in range(16):
                        if run.getpixel((frame * 16 + sx, sy)) == color:
                            cost = (sx - x) ** 2 + (sy - y) ** 2 + (0 if frame == preferred else .25)
                            candidates.append((cost, sy * run.width + frame * 16 + sx))
            assert candidates, (direction, x, y, color)
            lookup.append(min(candidates)[1])
    poses[direction] = {"frame": preferred, "pixels": lookup}

data = "// Generated by tools/flight-pose-gen.py from native authored idle anatomy.\n"
data += "window.JpoFlightPoseData = " + json.dumps(poses, separators=(",", ":")) + ";\n"
(ROOT / "public/flight-pose-data.js").write_text(data)
print("Generated directional flight pose lookup.")
